#!/usr/bin/env python3
"""components/display/test/faces/goldens.json -> faces_goldens.h (parameters of every golden case, in param_order)."""
import json
import sys

src, dst = sys.argv[1], sys.argv[2]
g = json.load(open(src, encoding="utf-8"))
order = g["param_order"]
out = ["/* GENERATED by test_host/gen_faces_h.py from goldens.json - do not edit. */\n",
       f"#define GOLDEN_N_PARAMS {len(order)}\n",
       "typedef struct { const char *name, *file; float blink; int wink; float p[GOLDEN_N_PARAMS]; } golden_case_t;\n",
       f"#define GOLDEN_N_CASES {len(g['cases'])}\n",
       "static const char *const golden_param_order[GOLDEN_N_PARAMS] = {" + ", ".join(f'"{n}"' for n in order) + "};\n",
       "static const golden_case_t golden_cases[GOLDEN_N_CASES] = {\n"]
for c in g["cases"]:
    vals = ", ".join(repr(float(c["params"][n])) + "f" for n in order)
    out.append(f'    {{"{c["name"]}", "{c["file"]}", {float(c["blink"])!r}f, {int(c["wink"])}, {{{vals}}}}},\n')
out.append("};\n")
open(dst, "w").write("".join(out))
