#!/usr/bin/env python3
"""Generate the firmware face library from the CANONICAL ai_stack/config/faces.json.

    python3 firmware/tools/gen_faces.py           # write
    python3 firmware/tools/gen_faces.py --check   # exit 1 if stale

Outputs (never edit by hand):
    zang_p4/components/display/include/faces_lib.h
    zang_p4/components/display/faces_lib.c
Each emotion is stored fully resolved (base + emotion overrides), plus its `_wink` flag, in param-id order.
"""
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
SRC = os.path.join(os.path.dirname(FW), "ai_stack", "config", "faces.json")
OUT = os.path.join(FW, "zang_p4", "components", "display")


def cf(x):
    t = repr(float(x))
    return (t if any(c in t for c in ".e") else t + ".0") + "f"


def render(lib, sha):
    params = sorted(lib["params"], key=lambda p: p["id"])
    if [p["id"] for p in params] != list(range(len(params))):
        sys.exit("faces.json: param ids must be 0..n-1")
    names = [p["name"] for p in params]
    for e in lib["emotions"]:
        bad = [k for k in e["p"] if k not in names and k != "_wink"]
        if bad:
            sys.exit(f"faces.json: emotion {e['name']} has unknown params {bad}")
    gen = "/* GENERATED by firmware/tools/gen_faces.py from ai_stack/config/faces.json - do not edit. */\n"
    h = [gen, "#pragma once\n\n#include <stdint.h>\n\n",
         f'#define FACES_SOURCE_SHA256 "{sha}"\n',
         f"#define FACE_N_PARAMS {len(params)}\n#define FACE_N_EMOTIONS {len(lib['emotions'])}\n",
         f"#define FACE_PANEL_W {lib['panel']['w']}\n#define FACE_PANEL_H {lib['panel']['h']}\n",
         f"#define FACE_PANEL_ROUND {1 if lib['panel']['round'] else 0}\n",
         "#define FACE_BG_R {}\n#define FACE_BG_G {}\n#define FACE_BG_B {}\n\n".format(*lib["panel"]["bg"]),
         "typedef enum {\n"]
    h += [f"    FP_{n.upper()} = {i},\n" for i, n in enumerate(names)]
    h.append("} face_param_id_t;\n\n")
    h.append("typedef enum {\n")
    h += [f"    FACE_EMO_{re.sub(r'[^A-Z0-9]', '_', e['name'].upper())} = {i},\n" for i, e in enumerate(lib["emotions"])]
    h.append("} face_emotion_id_t;\n\n")
    h.append("typedef struct {\n    const char *name;\n    float min, max;\n} face_param_info_t;\n\n")
    h.append("typedef struct {\n    const char *name;\n    float p[FACE_N_PARAMS]; /* fully resolved: base + emotion */\n"
             "    uint8_t wink;\n} face_emotion_t;\n\n")
    h.append("extern const face_param_info_t face_params_info[FACE_N_PARAMS];\n")
    h.append("extern const float face_base[FACE_N_PARAMS];\n")
    h.append("extern const face_emotion_t face_emotions[FACE_N_EMOTIONS];\n")

    c = [gen, '#include "faces_lib.h"\n\nconst face_param_info_t face_params_info[FACE_N_PARAMS] = {\n']
    c += [f'    {{"{p["name"]}", {cf(p["min"])}, {cf(p["max"])}}},\n' for p in params]
    c.append("};\n\nconst float face_base[FACE_N_PARAMS] = {" + ", ".join(cf(lib["base"][n]) for n in names) + "};\n\n")
    c.append("const face_emotion_t face_emotions[FACE_N_EMOTIONS] = {\n")
    for e in lib["emotions"]:
        full = dict(lib["base"])
        full.update({k: v for k, v in e["p"].items() if k != "_wink"})
        c.append(f'    {{"{e["name"]}", {{' + ", ".join(cf(full[n]) for n in names) +
                 f'}}, {1 if e["p"].get("_wink", 0) >= 0.5 else 0}}},\n')
    c.append("};\n")
    return "".join(h), "".join(c)


def main():
    raw = open(SRC, "rb").read()
    h, c = render(json.loads(raw), hashlib.sha256(raw).hexdigest())
    outs = {os.path.join(OUT, "include", "faces_lib.h"): h, os.path.join(OUT, "faces_lib.c"): c}
    stale = [p for p, t in outs.items() if not os.path.exists(p) or open(p).read() != t]
    if "--check" in sys.argv:
        print("faces_lib STALE: run firmware/tools/gen_faces.py" if stale else "faces_lib up to date")
        return 1 if stale else 0
    for p in stale:
        open(p, "w").write(outs[p])
    print(f"{'wrote ' + str(len(stale)) + ' file(s)' if stale else 'up to date'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
