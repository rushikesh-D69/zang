#!/usr/bin/env python3
"""Generate the firmware joint table from the CANONICAL joint table ai_stack/config/robot.json.

    python3 firmware/tools/gen_robot_joints.py           # write
    python3 firmware/tools/gen_robot_joints.py --check   # exit 1 if stale (CI / test_host runs this)

Outputs (never edit by hand):
    zang_p4/components/robot_def/include/robot_joints.h
    zang_p4/components/robot_def/robot_joints.c
The header records the SHA-256 of robot.json so a stale table is detectable on the robot too (HELLO_ACK fw info).
"""
import hashlib
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
ROOT = os.path.dirname(FW)
SRC = os.path.join(ROOT, "ai_stack", "config", "robot.json")
OUT = os.path.join(FW, "zang_p4", "components", "robot_def")
GROUPS = {"waist": "ROBOT_GROUP_WAIST", "leg": "ROBOT_GROUP_LEG", "arm": "ROBOT_GROUP_ARM"}


def load():
    raw = open(SRC, "rb").read()
    cfg = json.loads(raw)
    joints = sorted(cfg["joints"], key=lambda j: j["index"])
    n = cfg["n_joints"]
    errors = []
    if [j["index"] for j in joints] != list(range(n)):
        errors.append(f"indices must be 0..{n - 1} without gaps")
    ids = [j["servo_id"] for j in joints]
    if len(set(ids)) != len(ids):
        errors.append("servo_id values must be unique")
    if any(not (0 <= i <= 253) for i in ids):
        errors.append("servo_id must be 0..253 (254 = broadcast)")
    for j in joints:
        if not j["lower"] <= j["home"] <= j["upper"]:
            errors.append(f"{j['name']}: home outside [lower, upper]")
        if j["group"] not in GROUPS:
            errors.append(f"{j['name']}: unknown group {j['group']}")
        if j["group"] not in cfg["group_limits"]:
            errors.append(f"{j['name']}: no group_limits for {j['group']}")
    if n > 16:
        errors.append("ZLink joint mask is u16: at most 16 joints")
    if errors:
        sys.exit("robot.json invalid:\n  " + "\n  ".join(errors))
    return cfg, joints, hashlib.sha256(raw).hexdigest()


def cf(x):
    """C float literal: 0 -> 0.0f, 1.5708 -> 1.5708f, 1e-05 -> 1e-05f."""
    t = f"{x:.6g}"
    return (t if any(ch in t for ch in ".e") else t + ".0") + "f"


def render(cfg, joints, sha):
    n = cfg["n_joints"]
    servo = cfg["servo"]
    ticks_range = servo["ticks_per_rev_placeholder"]
    range_deg = servo["range_deg_placeholder"]
    ticks_per_rev = round(ticks_range * 360.0 / range_deg)
    gen = "/* GENERATED by firmware/tools/gen_robot_joints.py from ai_stack/config/robot.json - do not edit. */\n"
    h = [gen, "#pragma once\n\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n",
         f'#define ROBOT_NAME "{cfg["name"]}"\n',
         f"#define ROBOT_N_JOINTS {n}\n",
         f'#define ROBOT_JOINTS_SOURCE_SHA256 "{sha}"\n',
         f'#define ROBOT_SERVO_MODEL "{servo["model"]}"\n',
         f"#define ROBOT_SERVO_BAUD_DEFAULT {servo['bus_baud_default']}\n",
         f"/* Servo resolution PLACEHOLDER: {ticks_range} ticks over {range_deg} deg -> ticks per 360 deg: */\n",
         f"#define ROBOT_SERVO_TICKS_PER_REV_DEFAULT {ticks_per_rev}\n",
         f"#define ROBOT_SERVO_TICK_MAX_DEFAULT {ticks_range - 1}\n\n",
         "typedef enum {\n"]
    h += [f"    ROBOT_J_{j['name'].upper()} = {j['index']},\n" for j in joints]
    h.append("} robot_joint_id_t;\n\n")
    h.append("typedef enum { " + ", ".join(f"{v} = {i}" for i, v in enumerate(GROUPS.values())) + " } robot_group_t;\n\n")
    h.append("typedef struct {\n    const char *name;\n    uint8_t servo_id;\n    robot_group_t group;\n"
             "    float lower_rad, upper_rad, home_rad;\n    float vmax_rad_s, amax_rad_s2;\n} robot_joint_def_t;\n\n")
    h.append("extern const robot_joint_def_t robot_joints[ROBOT_N_JOINTS];\n\n")
    h.append("#ifdef __cplusplus\n}\n#endif\n")

    c = [gen, '#include "robot_joints.h"\n\nconst robot_joint_def_t robot_joints[ROBOT_N_JOINTS] = {\n']
    for j in joints:
        gl = cfg["group_limits"][j["group"]]
        c.append(f'    [ROBOT_J_{j["name"].upper()}] = {{"{j["name"]}", {j["servo_id"]}, {GROUPS[j["group"]]}, '
                 f'{cf(j["lower"])}, {cf(j["upper"])}, {cf(j["home"])}, {cf(gl["vmax"])}, {cf(gl["amax"])}}},\n')
    c.append("};\n")
    return "".join(h), "".join(c)


def main():
    cfg, joints, sha = load()
    h, c = render(cfg, joints, sha)
    outs = {os.path.join(OUT, "include", "robot_joints.h"): h, os.path.join(OUT, "robot_joints.c"): c}
    stale = [p for p, t in outs.items() if not os.path.exists(p) or open(p).read() != t]
    if "--check" in sys.argv:
        if stale:
            print("robot_joints is STALE vs ai_stack/config/robot.json; run firmware/tools/gen_robot_joints.py")
            return 1
        print("robot_joints up to date")
        return 0
    for p in stale:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(outs[p])
    print(f"{len(joints)} joints, {'wrote ' + str(len(stale)) + ' file(s)' if stale else 'up to date'} (sha {sha[:12]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
