# Pins the board uses for things firmware does not configure.
SYSTEM_PINS = {24: "USB D- (USB-Serial-JTAG)", 25: "USB D+", 35: "BOOT_P4 strap (10k up + button)",
               36: "strap, 10k pull-up R24"}


def _validate():
    seen = {}
    for _, n, d, _, _ in PINS:
        if d < 0:
            continue
        if d in seen or d in SYSTEM_PINS:
            raise SystemExit(f"default GPIO{d} used twice ({n} and {seen.get(d, SYSTEM_PINS.get(d))})")
        seen[d] = n


HEADER = "/* GENERATED by firmware/tools/gen_board_pins.py - do not edit. */\n"


def kconfig():
    out = ["# GENERATED by firmware/tools/gen_board_pins.py - do not edit. Sourced by Kconfig.\n"]
    group = None
    for g, n, dflt, net, d in PINS:
        if g != group:
            if group is not None:
                out.append("endmenu\n")
            out.append(f'menu "{g.capitalize()} pins"\n')
            group = g
        out.append(f"config ZANG_PIN_{n}\n    int \"{n} (net {net})\"\n    range -1 54\n    default {dflt}\n"
                   f"    help\n        {d}. Schematic v0.0.1 default: {dflt}. -1 = not assigned: the driver that\n"
                   f"        needs it is skipped at boot.\n\n")
    out.append("endmenu\n")
    return "".join(out)


def header():
    lines = [HEADER, "#pragma once\n\n#include \"sdkconfig.h\"\n\n"]
    for _, n, _dflt, _net, d in PINS:
        lines.append(f"#define BOARD_PIN_{n:<14} CONFIG_ZANG_PIN_{n} /* {d} */\n")
    lines.append(f"\n#define BOARD_PIN_COUNT {len(PINS)}\n")
    return "".join(lines)


def table():
    lines = [HEADER, '#include "board.h"\n#include "board_pins.h"\n\n',
             "const board_pin_t board_pin_table[BOARD_PIN_COUNT] = {\n"]
    for g, n, _dflt, _net, _d in PINS:
        lines.append(f'    {{"{g}", "{n}", BOARD_PIN_{n}}},\n')
    lines.append("};\n")
    return "".join(lines)


def pinout_table():
    rows = ["| Group | Kconfig `CONFIG_ZANG_PIN_…` | Schematic net | GPIO (default) | Notes |", "|---|---|---|---|---|"]
    for g, n, dflt, net, d in PINS:
        gp = f"**{dflt}**" if dflt >= 0 else "—"
        rows.append(f"| {g} | `{n}` | {net} | {gp} | {d} |")
    used = {d for _, _, d, _, _ in PINS if d >= 0} | SYSTEM_PINS.keys()
    free = [g for g in range(55) if g not in used]
    notes = []
    for g in free:
        if g in (34, 37, 38):
            notes.append(f"{g} (strap: leave free)")
        elif g in (0, 1):
            notes.append(f"{g} (32 kHz XTAL pads)")
        elif g in (2, 3, 4):
            notes.append(f"{g} (pad JTAG)")
        else:
            notes.append(str(g))
    rows.append("")
    rows.append("Fixed by the board (not configurable): " +
                ", ".join(f"GPIO{g} = {what}" for g, what in sorted(SYSTEM_PINS.items())) + ".")
    rows.append("")
    rows.append("**Free GPIOs on v0.0.1:** " + ", ".join(notes) + ".")
    return "\n".join(rows) + "\n"


def splice(path, body):
    start, end = "<!-- GENERATED:PINS:BEGIN -->\n", "<!-- GENERATED:PINS:END -->"
    text = open(path).read() if os.path.exists(path) else f"# Pinout\n\n{start}{end}\n"
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + body + text[b:]


def main():
    _validate()
    check = "--check" in sys.argv
    outputs = {
        os.path.join(BOARD, "Kconfig.pins"): kconfig(),
        os.path.join(BOARD, "include", "board_pins.h"): header(),
        os.path.join(BOARD, "board_pin_table.c"): table(),
    }
    pinout = os.path.join(FW, "docs", "PINOUT.md")
    outputs[pinout] = splice(pinout, pinout_table())
    stale = []
    for path, text in outputs.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w").write(text)
    if check and stale:
        print("stale:", *stale, sep="\n  ")
        return 1
    print(("up to date" if not stale else f"wrote {len(stale)} file(s)") + f", {len(PINS)} pins")
    return 0


if __name__ == "__main__":
    sys.exit(main())
